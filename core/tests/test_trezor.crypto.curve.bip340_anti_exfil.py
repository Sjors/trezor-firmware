    def test_roundtrip(self):
        for vector in self.vectors:
            sk, msg, h, nonce, rho, expected = (bytes.fromhex(x) for x in vector)
            self.assertEqual(bip340.anti_exfil(sk, msg, h, None, None), nonce)
            sig = bip340.anti_exfil(sk, msg, h, nonce, rho)
            self.assertEqual(sig, expected)
            self.assertTrue(bip340.verify(bip340.publickey(sk), sig, msg))
            with self.assertRaises(ValueError):
                bip340.anti_exfil(sk, msg, h, bytes([nonce[0] ^ 1]) + nonce[1:], rho)
            with self.assertRaises(ValueError):
                bip340.anti_exfil(sk, msg, h, nonce, bytes(32))
            with self.assertRaises(ValueError):
                bip340.anti_exfil(sk, msg, h, None, rho)
            with self.assertRaises(ValueError):
                bip340.anti_exfil(sk, msg, h, nonce, None)


